"""Rebuild the embedded emoji atlas (Python + Pillow; downloads pinned Twemoji PNGs)."""
import io
import json
from pathlib import Path
from urllib.request import urlopen
from PIL import Image

ROOT = Path(__file__).resolve().parent
GROUPS = {
    "Food": "1f356 Meat,1f357 Poultry,1f41f Fish,1f35e Bread,1f9c0 Cheese,1f95a Egg,1f344 Mushroom,1f34e Apple,1f353 Berry,1f952 Cucumber,1f955 Carrot,1f33d Corn,1f36f Honey,1f37a Ale,1f372 Soup,1f347 Grapes",
    "Materials": "1fab5 Wood,1faa8 Stone,1f525 Fire,1f4a7 Water,1f33e Grain,1f331 Seedling,1f33b Flower,1f332 Fir,1f333 Tree,1f343 Leaves,1f48e Gem,1f9f1 Brick,1f9f5 Thread,1f9f6 Yarn,1fab6 Feather,1f9b4 Bone",
    "Equipment": "1fa93 Axe,1f528 Hammer,1f527 Wrench,1f529 Parts,1f9f2 Magnet,1f3f9 Bow,1f6e1 Shield,1f5e1 Sword,1f9ea Potion,1f9f0 Tools,1f392 Backpack,1f45e Shoes,1f451 Crown,1f48d Ring,1f511 Key,1f512 Lock",
    "Places": "1f3e0 Home,1f3f0 Castle,1f6aa Door,1f6cf Bed,1f4e6 Storage,1f6a2 Ship,1f6f6 Canoe,1f9ed Compass,1f5fa Map,1f3d4 Mountain,1f30a Ocean,1f480 Danger,1f6ab Forbidden,1f6a9 Flag,1f4a1 Idea,1f31f Star",
}

def main():
    manifest_path = ROOT / "atlas.json"
    previous = json.loads(manifest_path.read_text()) if manifest_path.exists() else None
    commit = previous["commit"] if previous else json.load(urlopen("https://api.github.com/repos/jdecked/twemoji/commits/main"))["sha"]
    base = f"https://raw.githubusercontent.com/jdecked/twemoji/{commit}/"
    atlas = Image.new("RGBA", (608, 608)) # 8 x 8, 72px artwork + 2px padding each side
    entries = []
    for group, values in GROUPS.items():
        for item in values.split(","):
            code, name = item.split(" ", 1)
            index = len(entries)
            data = urlopen(base + f"assets/72x72/{code}.png").read()
            icon = Image.open(io.BytesIO(data)).convert("RGBA")
            assert icon.size == (72, 72)
            atlas.paste(icon, ((index % 8) * 76 + 2, (index // 8) * 76 + 2))
            entries.append({"unicode": int(code, 16), "name": name, "group": group})
    assert len(entries) == 64
    atlas.save(ROOT / "atlas.png")
    manifest_path.write_text(json.dumps({"commit": commit, "entries": entries}, indent=2) + "\n")
    (ROOT / "LICENSE-GRAPHICS.txt").write_bytes(urlopen(base + "LICENSE-GRAPHICS").read())
    lines = ["// Generated by BuildAtlas.py. Order matches atlas.png.", "namespace Runic.Shared;", "internal static partial class EmojiCatalog", "{", "    internal static readonly EmojiEntry[] Entries =", "    {"]
    for e in entries:
        lines.append(f'        new(0x{e["unicode"]:X}, "{e["name"]}", "{e["group"]}"),')
    (ROOT / "EmojiCatalog.Generated.cs").write_text("\n".join(lines + ["    };", "}", ""]))
    print(f"Built {len(entries)} emojis from Twemoji {commit}")

if __name__ == "__main__":
    main()
